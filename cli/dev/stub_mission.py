#!/usr/bin/env python3
"""A scripted stand-in for a model, so a whole mission can be watched with no key.

The real thing needs a vendor and a bill. This server speaks the OpenAI chat-completions
shape the CLI's `openai-chat` adapter expects, and plays the three roles a mission needs:

  * **plan**  — Strategos is asked to split the task; it answers with an assignments JSON.
  * **work**  — each operator is recognised by its code in the system prompt
                (`You are x1-write …`); on its first turn it calls `write_file`, on its
                second it reports back in prose.
  * **review**— Strategos is asked to judge the reports; everything clean is accepted.

The prompts are the real ones — generated by `zenithal_agent::strategos` — so this is a
faithful rehearsal of the protocol: only the words coming back are canned.

    python3 cli/dev/stub_mission.py --port 8099 &

    mkdir -p /tmp/demo-repo && cd /tmp/demo-repo && git init -q && git commit -q --allow-empty -m init
    export ZENITHAL_HOME=/tmp/demo-home ZENITHAL_STUB_KEY=not-a-key
    mkdir -p $ZENITHAL_HOME/.zenithal
    cat > $ZENITHAL_HOME/.zenithal/config.json <<'JSON'
    { "memory": { "backend": "file" },
      "providers": { "default": "openai-chat", "model": "stub",
                     "base_url": "http://127.0.0.1:8099", "api_key_env": "ZENITHAL_STUB_KEY" } }
    JSON

    zenithal mission run "add one file per code" --repo /tmp/demo-repo --parallel 1

Every request is logged to stderr, so you can see exactly what the binary sent.
"""

import argparse
import json
import re

# The catalogue the real prompt carries, in the same order as `zenithal-brand`'s table.
CODES = [
    "x0-core",
    "x1-write",
    "x2-check",
    "x3-ship",
    "x4-scan",
    "x5-patch",
    "x6-audit",
    "x7-trace",
]
CODE_RE = re.compile(r"x\d+-[a-z]+(?:-\d+)?")

# `--lazy` makes every operator answer with prose and touch nothing, which is how the
# failure paths (`no operator produced an applicable change`, exit 1) are rehearsed by hand.
LAZY = False
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer



def text_of(content):
    """A chat message's content is a string, or a list of parts."""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return " ".join(p.get("text", "") for p in content if isinstance(p, dict))
    return ""


def reply(content=None, tool_call=None):
    message = {"role": "assistant", "content": content}
    if tool_call:
        name, args = tool_call
        message["tool_calls"] = [
            {"id": "call_1", "type": "function", "function": {"name": name, "arguments": json.dumps(args)}}
        ]
    return {
        "id": "chatcmpl-stub",
        "object": "chat.completion",
        "model": "stub",
        "choices": [{"index": 0, "message": message, "finish_reason": "tool_calls" if tool_call else "stop"}],
        "usage": {"prompt_tokens": 100, "completion_tokens": 20, "total_tokens": 120},
    }


def decide(body):
    messages = body.get("messages") or []
    system = text_of(messages[0].get("content")) if messages else ""
    tool_messages = [m for m in messages if m.get("role") == "tool"]
    # Codes appear in the system prompt when planning and in the user turn when reviewing,
    # so both are searched.
    whole = system + "\n" + "\n".join(text_of(m.get("content")) for m in messages)

    # Strategos, judging what came back. The reports are keyed by code.
    if "have returned from their assignments" in system:
        codes = sorted(set(re.findall(CODE_RE.pattern, whole)))
        return reply(json.dumps({
            "verdicts": [
                {"codename": c, "accept": True, "reason": "wrote exactly the file it was given"}
                for c in codes
            ]
        }))

    # Strategos, planning: hand each slot a code from the catalogue.
    if "The Phalanx" in system and "short-hand system codes" in system:
        slots = sorted(set(re.findall(r"slot-\d+", whole)))
        return reply(json.dumps({
            "assignments": [
                {
                    "codename": slot,
                    "code": CODES[i % len(CODES)],
                    "task": f"create {CODES[i % len(CODES)]}.txt containing the word "
                            f"{CODES[i % len(CODES)].split('-')[1]}",
                }
                for i, slot in enumerate(slots)
            ]
        }))

    # An operator, working. Stateless on purpose: the conversation itself says whether this
    # is the first turn (no tool result yet) or the report-back turn, so any number of
    # operators can be in flight at once and the stub needs no bookkeeping.
    match = re.search(r"You are (x\d+-[a-z0-9-]+)", system)
    if match:
        code = match.group(1)
        path = f"{code}.txt"
        if LAZY:
            return reply(f"{code} reporting: nothing to change here.")
        if not tool_messages:
            return reply(tool_call=("write_file", {"path": path, "content": f"{code}\n"}))
        return reply(f"{code} reporting: wrote {path}.")

    return reply("This stub only knows how to be Strategos or an operator of the Phalanx.")


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def do_POST(self):  # noqa: N802 (stdlib naming)
        length = int(self.headers.get("content-length", "0"))
        raw = self.rfile.read(length)
        try:
            body = json.loads(raw or b"{}")
        except json.JSONDecodeError:
            body = {}

        messages = body.get("messages") or []
        first = text_of(messages[0].get("content")) if messages else ""
        print(f"\n--- POST {self.path}  model={body.get('model')}  messages={len(messages)}", flush=True)
        print("    system: " + first.splitlines()[0][:120] if first else "    system: (none)", flush=True)

        payload = json.dumps(decide(body)).encode()
        self.send_response(200)
        self.send_header("content-type", "application/json")
        self.send_header("content-length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)
        self.wfile.flush()

    def log_message(self, *args):
        pass


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8099)
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument(
        "--lazy",
        action="store_true",
        help="operators answer but change nothing, to exercise the failure paths",
    )
    args = parser.parse_args()
    global LAZY
    LAZY = args.lazy
    server = ThreadingHTTPServer((args.host, args.port), Handler)
    mode = "lazy" if LAZY else "working"
    print(f"stub mission server on http://{args.host}:{args.port} ({mode})", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
